"""Training-only causal diagnostic; default is offline validation, --run spends inference.

Both arms use the deployed e3 model through the unchanged production agent.
The intervention supplies an authentic teacher plan/result as observable history.
It does not execute that teacher call again or pretend it was generated by e3.
All diagnostic captures are excluded from training eligibility.
"""

import argparse
import asyncio
from contextlib import contextmanager
from contextvars import ContextVar
from copy import deepcopy
from dataclasses import replace
import hashlib
import importlib.util
import json
from pathlib import Path

import bufogen.agents.agent as agent_module
import bufogen.evaluation.benchmark as benchmark
from bufogen.models import load_backends
from bufogen.settings import ROOT
from bufogen.curation.trajectories import response_items

ORDINARY = "ordinary_plan"
SUPPLIED = "teacher_plan_continuation"
POLICY = dict(concurrency=8, temperature=0.0, max_tokens=6000, max_turns=8)
CONTEXT = ContextVar("bufo_plan_continuation", default=None)
BASE = "google/gemma-4-26B-A4B-it"
TEACHER = "gpt-6.1-sol"


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def jsonl(path):
    return [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]


def teacher_plan(example):
    """Select actual adjacent plan call/result, never fabricate or rewrite either."""
    messages = example["messages"]
    selected = None
    for index, message in enumerate(messages):
        calls = message.get("tool_calls", [])
        if any(c["function"]["name"] == "render_svg" for c in calls):
            break
        if len(calls) != 1 or calls[0]["function"]["name"] != "plan_scene":
            continue
        if index + 1 >= len(messages):
            continue
        result = messages[index + 1]
        if result.get("role") != "tool" or result.get("tool_call_id") != calls[0]["id"]:
            continue
        output = json.loads(result["content"])
        arguments = json.loads(calls[0]["function"]["arguments"])
        if (
            output.get("version") == "bufo-scene-plan-v1"
            and not output.get("warnings")
            and arguments.get("contact_anchors")
        ):
            selected = deepcopy([message, result])
    if selected is None:
        raise ValueError("No authentic successful contact plan before first render")
    return {
        "source_model": example["source_model"],
        "source_generation_id": example["source_generation_id"],
        "source_prompt_id": example["prompt_id"],
        "messages": selected,
        "items": response_items(selected),
        "messages_sha256": benchmark.digest(selected),
    }


def verify_fit_scores(rows, prompts):
    """Ensure contact failures came from supplied checks, not absent/malformed metadata."""
    by_id = {p["id"]: p for p in prompts}
    if len(rows) != 16 or {r["prompt_id"] for r in rows} != set(by_id):
        raise ValueError("Expected all sixteen fixed contact-fit results")
    for row in rows:
        requirements = by_id[row["prompt_id"]]["requirements"]
        result = row["scores"]["scene_quality"]
        checks = result.get("prompt_checks", [])
        if (
            row["benchmark_metadata"]["requirements"] != requirements
            or result.get("requirements") != requirements
            or result.get("status") != "ok"
            or len(checks) != len(requirements)
            or sorted(c["requirement"] for c in checks) != sorted(requirements)
            or any(type(c.get("satisfied")) is not bool for c in checks)
            or result["constraint_coverage"] != sum(c["satisfied"] for c in checks) / len(checks)
        ):
            raise ValueError("Fit scoring input/checklist/coverage inconsistency")
    return {
        "rows": len(rows),
        "checklist_and_coverage_consistent": True,
        "zero_coverage_rows": sum(r["scores"]["scene_quality"]["constraint_coverage"] == 0 for r in rows),
        "scope": "Schema/arithmetic check only; pixel judgments remain uncalibrated.",
    }


def prepare(root):
    root = Path(root).resolve()
    fit = root / "training-fit-selected"
    source = root / "training/reviewed-examples.jsonl"
    state_path = root / "training/e3/forge-state.json"
    selection_path = root / "selection.json"
    state, selection = read(state_path), read(selection_path)
    chosen = selection["candidates"]["open_tuned_epoch3"]
    if (
        selection["selected_arm"] != "open_tuned_epoch3"
        or selection["selected_artifact"] != state["model_artifact_ref"]
        or chosen["state_sha256"] != sha(state_path)
        or state.get("status") != "deployed"
        or state.get("pending_operation")
        or state["base_model"] != BASE
        or state["training_config"] != {
            "epochs": 3, "batch_size": 2, "assistant_turns": "all", "learning_rate": 1e-4
        }
        or state["source_sha256"] != sha(source)
    ):
        raise ValueError("Expected immutable deployed iteration-two e3 source/selection")
    settings = read(fit / "benchmark.json")
    config = settings["configuration"]
    prompts = config["prompts"]
    if (
        len(prompts) != 16
        or len({p["family"] for p in prompts}) != 16
        or any(p["split"] != "train" or not p["id"].endswith("-contact") for p in prompts)
        or config["source_hashes"] != benchmark._source_hashes()
    ):
        raise ValueError("Fixed training contact set or runtime bytes changed")
    examples = {r["prompt_id"]: r for r in jsonl(source)}
    fit_rows = jsonl(fit / "scored.jsonl")
    score_audit = verify_fit_scores(fit_rows, prompts)
    fit_by_id = {r["prompt_id"]: r for r in fit_rows}
    plans = {}
    for prompt in prompts:
        example = examples[prompt["id"]]
        previous = fit_by_id[prompt["id"]]["trajectory"]
        review = example["training_review"]
        if (
            example["partition"] != "train"
            or example["source_model"] != TEACHER
            or example["prompt"] != prompt["prompt"]
            or review["decision"] != "accept"
            or review["visual_quality_pass"] is not True
            or sha(review["source_ref"]) != review["png_sha256"]
            or example["messages"][:2] != previous["messages"][:2]
            or example["tools"] != previous["tools"]
        ):
            raise ValueError("Reviewed teacher and exact fit request/schema do not match")
        plans[prompt["id"]] = teacher_plan(example)
    backend = replace(
        load_backends()["open_tuned"], model=state["model_artifact_ref"],
        base_model=BASE, label="ft-" + BASE, tuning_method="sft",
    )
    arms = [replace(backend, name=name) for name in (ORDINARY, SUPPLIED)]
    protocol = {
        "schema_version": 1,
        "diagnostic": "teacher-plan-continuation-v1",
        "interpretation": "Training-only intervention; not a heldout or model improvement claim.",
        "training_eligible": False,
        "model": state["model_artifact_ref"],
        "policy": POLICY,
        "source_sha256": {
            str(path): sha(path) for path in (
                source, state_path, selection_path, fit / "benchmark.json",
                fit / "scored.jsonl", Path(__file__).resolve(),
            )
        },
        "plans": plans,
        "prompts": prompts,
        "fit_score_audit": score_audit,
        "intervention": (
            "Append the exact reviewed teacher plan call/result after the unchanged user input. "
            "Ordinary arm receives no prefix. Both may revise plans. Eight generated model turns "
            "per Runner invocation; injected teacher history does not consume that budget."
        ),
    }
    return prompts, arms, protocol


@contextmanager
def diagnostic_hooks(plans):
    """Process-local, task-scoped hooks; production source and public API stay unchanged."""
    original_input = agent_module.conversation_input
    original_capture = agent_module.capture_trajectory
    original_agent = benchmark.BufoAgent

    def conversation_input(prompt, *, history=None, image=None):
        messages, authentic = original_input(prompt, history=history, image=image)
        context = CONTEXT.get()
        if context and context["arm"] == SUPPLIED:
            if history or image or len(messages) != 1:
                raise ValueError("Diagnostic only supports a fresh text request")
            messages.extend(deepcopy(context["plan"]["items"]))
            authentic = False  # Authentic teacher artifact, not authentic student-owned history.
        return messages, authentic

    def capture_trajectory(**kwargs):
        captured = original_capture(**kwargs)
        context = CONTEXT.get()
        if context:
            captured["diagnostics"].append("controlled training-only diagnostic; not training eligible")
            captured["provenance"]["diagnostic"] = deepcopy(context)
            captured["provenance"]["training_eligible"] = False
            if context["arm"] == SUPPLIED:
                captured["provenance"]["source_models"] = [
                    context["plan"]["source_model"], kwargs["provenance"]["model"]
                ]
                captured["diagnostics"].append("trajectory contains mixed-model teacher plan context")
        return captured

    class DiagnosticAgent(original_agent):
        async def generate(self, prompt, **kwargs):
            context = {"arm": self.backend.name, "training_eligible": False}
            if self.backend.name == SUPPLIED:
                context["plan"] = plans[kwargs["prompt_id"]]
            token = CONTEXT.set(context)
            try:
                return await super().generate(prompt, **kwargs)
            finally:
                CONTEXT.reset(token)

    agent_module.conversation_input = conversation_input
    agent_module.capture_trajectory = capture_trajectory
    benchmark.BufoAgent = DiagnosticAgent
    try:
        yield
    finally:
        agent_module.conversation_input = original_input
        agent_module.capture_trajectory = original_capture
        benchmark.BufoAgent = original_agent


async def run(root, output, *, publish=True):
    prompts, arms, protocol = prepare(root)
    # Read-only service verification before paid inference, using the audited helper.
    spec = importlib.util.spec_from_file_location("iteration2_evaluation", ROOT / "docs/forge-iteration2/evaluate.py")
    evaluator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(evaluator)
    verified = evaluator.verify_new_candidate(root, "open_tuned_epoch3")
    if verified["artifact"] != protocol["model"]:
        raise ValueError("Live adapter differs from frozen diagnostic")
    output = Path(output).resolve()
    with benchmark._locked(output):
        path = output / "diagnostic-protocol.json"
        if path.exists():
            if read(path) != protocol:
                raise ValueError("Diagnostic source/protocol changed; cannot resume")
        else:
            if (output / "benchmark.json").exists() or (output / "manifest.jsonl").exists():
                raise ValueError("Cannot adopt existing outputs without diagnostic protocol")
            benchmark._write_json(path, protocol)
            (output / "plan_continuation.py").write_bytes(Path(__file__).read_bytes())
    from bufogen.integrations.telemetry import init_weave
    client = init_weave()
    try:
        with diagnostic_hooks(protocol["plans"]):
            await benchmark.run_benchmark(prompts, arms, output, **POLICY)
        await benchmark.score_benchmark(output, concurrency=8, publish=publish)
        return read(output / "summary.json")
    finally:
        client.finish()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT / "runs/forge-iteration2")
    parser.add_argument("--output", type=Path, default=ROOT / "runs/forge-iteration2/plan-continuation")
    parser.add_argument("--run", action="store_true", help="Execute paid generation and scoring")
    parser.add_argument("--no-publish", action="store_true", help="Skip native eval publication; generation traces still log")
    args = parser.parse_args()
    if args.run:
        print(json.dumps(asyncio.run(run(args.root, args.output, publish=not args.no_publish)), indent=2))
    else:
        prompts, arms, protocol = prepare(args.root)
        print(json.dumps({
            "dry_validation": "passed", "network_calls": 0, "prompts": len(prompts),
            "arms": [a.name for a in arms], "model": protocol["model"],
            "attempts": len(prompts) * len(arms), "fit_score_audit": protocol["fit_score_audit"],
            "training_eligible": False,
        }, indent=2))


if __name__ == "__main__":
    main()
